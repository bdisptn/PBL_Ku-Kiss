CREATE TABLE IF NOT EXISTS admin (
  id_admin INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  nama VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS kategori (
  id_kategori INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_kategori VARCHAR(20) NOT NULL UNIQUE,
  nama_kategori VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS pelanggan (
  id_pelanggan INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  email VARCHAR(100) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  nama VARCHAR(100),
  no_telp VARCHAR(20),
  alamat TEXT,
  foto VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS produk (
  id_produk INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_produk VARCHAR(100) NOT NULL,
  deskripsi TEXT,
  harga NUMERIC(12, 2) NOT NULL CHECK (harga >= 0),
  gambar VARCHAR(255),
  kode_produk VARCHAR(30) UNIQUE,
  id_kategori INTEGER REFERENCES kategori(id_kategori) ON UPDATE CASCADE ON DELETE SET NULL
);

ALTER TABLE produk DROP COLUMN IF EXISTS stok;

CREATE TABLE IF NOT EXISTS batch_po (
  id_batch INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_admin INTEGER NOT NULL REFERENCES admin(id_admin) ON UPDATE CASCADE ON DELETE RESTRICT,
  nama_batch VARCHAR(100) NOT NULL UNIQUE,
  tanggal_buka DATE NOT NULL,
  tanggal_tutup DATE NOT NULL CHECK (tanggal_tutup >= tanggal_buka),
  status_batch VARCHAR(20) NOT NULL DEFAULT 'dibuka'
    CHECK (status_batch IN ('dibuka', 'ditutup', 'diproduksi', 'selesai'))
);

CREATE TABLE IF NOT EXISTS pesanan (
  id_pesanan INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_pesanan VARCHAR(20) NOT NULL UNIQUE,
  id_pelanggan INTEGER NOT NULL REFERENCES pelanggan(id_pelanggan) ON UPDATE CASCADE ON DELETE RESTRICT,
  id_admin INTEGER REFERENCES admin(id_admin) ON UPDATE CASCADE ON DELETE SET NULL,
  id_batch INTEGER NOT NULL REFERENCES batch_po(id_batch) ON UPDATE CASCADE ON DELETE RESTRICT,
  tanggal_pesan TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  metode_pengambilan VARCHAR(20) NOT NULL DEFAULT 'pickup'
    CHECK (metode_pengambilan IN ('pickup', 'delivery')),
  tanggal_ambil DATE,
  status_pesanan VARCHAR(30) NOT NULL DEFAULT 'Diproses'
    CHECK (status_pesanan IN ('Diproses', 'Siap Diambil', 'Selesai', 'Dibatalkan')),
  status_pembayaran VARCHAR(30) NOT NULL DEFAULT 'Belum Dibayar'
    CHECK (status_pembayaran IN ('Belum Dibayar', 'Lunas', 'Ditolak')),
  metode_pembayaran VARCHAR(30)
    CHECK (metode_pembayaran IN ('Tunai', 'QRIS', 'Transfer')),
  total_harga NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (total_harga >= 0),
  alamat_pengiriman TEXT,
  ongkir NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (ongkir >= 0),
  bukti_pembayaran VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS detail_pesanan (
  id_detail INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pesanan INTEGER NOT NULL REFERENCES pesanan(id_pesanan) ON UPDATE CASCADE ON DELETE CASCADE,
  id_produk INTEGER NOT NULL REFERENCES produk(id_produk) ON UPDATE CASCADE ON DELETE RESTRICT,
  jumlah INTEGER NOT NULL CHECK (jumlah > 0),
  subtotal NUMERIC(12, 2) NOT NULL CHECK (subtotal >= 0)
);

CREATE TABLE IF NOT EXISTS pengeluaran (
  id_pengeluaran INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_batch INTEGER NOT NULL REFERENCES batch_po(id_batch) ON UPDATE CASCADE ON DELETE CASCADE,
  keterangan VARCHAR(150),
  total_pengeluaran NUMERIC(12, 2) NOT NULL CHECK (total_pengeluaran >= 0),
  tanggal_pengeluaran DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE IF NOT EXISTS login_percobaan (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  identifier VARCHAR(190) NOT NULL,
  ip VARCHAR(45) NOT NULL,
  berhasil BOOLEAN NOT NULL DEFAULT FALSE,
  waktu TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS notifikasi (
  id_notifikasi INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pesanan INTEGER NOT NULL REFERENCES pesanan(id_pesanan) ON UPDATE CASCADE ON DELETE CASCADE,
  jenis_notifikasi VARCHAR(60) NOT NULL,
  isi_pesan TEXT NOT NULL,
  status_kirim VARCHAR(20) NOT NULL DEFAULT 'menunggu'
    CHECK (status_kirim IN ('menunggu', 'terkirim', 'gagal')),
  waktu_kirim TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_detail_pesanan_pesanan ON detail_pesanan (id_pesanan);
CREATE INDEX IF NOT EXISTS idx_detail_pesanan_produk ON detail_pesanan (id_produk);
CREATE INDEX IF NOT EXISTS idx_login_percobaan ON login_percobaan (identifier, ip, waktu);
CREATE INDEX IF NOT EXISTS idx_notifikasi_pesanan ON notifikasi (id_pesanan);
CREATE INDEX IF NOT EXISTS idx_pengeluaran_batch ON pengeluaran (id_batch);
CREATE INDEX IF NOT EXISTS idx_pesanan_batch ON pesanan (id_batch);
CREATE INDEX IF NOT EXISTS idx_pesanan_pelanggan ON pesanan (id_pelanggan);
CREATE INDEX IF NOT EXISTS idx_pesanan_status_pembayaran ON pesanan (status_pembayaran);
CREATE INDEX IF NOT EXISTS idx_pesanan_tanggal ON pesanan (tanggal_pesan);
CREATE INDEX IF NOT EXISTS idx_produk_kategori ON produk (id_kategori);

